export const GLYPHS = {};
for (const [k, rows] of Object.entries(G)) {
  GLYPHS[k] = rows.map((r) => [...r].map((c) => (c === '#' ? 1 : 0)));
}
export const GW = 5, GH = 7, ADV = 6;

export function glyph(ch) {
  return GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
}

export function textWidth(s, scale = 1) {
  return s.length * ADV * scale - scale;
}

// Draw into a Uint32 pixel buffer (w x h) with a solid colour word.
export function drawText(buf, w, h, s, x0, y0, color, scale = 1, shadow = null) {
  if (shadow !== null) drawText(buf, w, h, s, x0 + scale, y0 + scale, shadow, scale, null);
  let x = x0 | 0;
  for (const ch of s) {
    const g = glyph(ch);
    for (let gy = 0; gy < GH; gy++) {
      const row = g[gy];
      for (let gx = 0; gx < GW; gx++) {
        if (!row[gx]) continue;
        for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) {
          const px = x + gx * scale + sx, py = (y0 | 0) + gy * scale + sy;
          if (px >= 0 && py >= 0 && px < w && py < h) buf[py * w + px] = color;
        }
      }
    }
    x += ADV * scale;
  }
}

// Stroke skeleton for "handwriting": connect 8-neighbour set pixels.
const STROKE_CACHE = {};
export function glyphStrokes(ch) {
  if (STROKE_CACHE[ch]) return STROKE_CACHE[ch];
  const g = glyph(ch);
  const segs = [];
  const on = (x, y) => y >= 0 && y < GH && x >= 0 && x < GW && g[y][x];
  for (let y = 0; y < GH; y++) for (let x = 0; x < GW; x++) {
    if (!on(x, y)) continue;
    let any = false;
    // right, down, diag-down-right, diag-down-left (avoid diagonals when orthogonal path exists)
    if (on(x + 1, y)) { segs.push([x, y, x + 1, y]); any = true; }
    if (on(x, y + 1)) { segs.push([x, y, x, y + 1]); any = true; }
    if (on(x + 1, y + 1) && !on(x + 1, y) && !on(x, y + 1)) { segs.push([x, y, x + 1, y + 1]); any = true; }
    if (on(x - 1, y + 1) && !on(x - 1, y) && !on(x, y + 1)) { segs.push([x, y, x - 1, y + 1]); any = true; }
    if (!any && !on(x - 1, y) && !on(x, y - 1) && !on(x - 1, y - 1) && !on(x + 1, y - 1)) segs.push([x, y, x + 0.2, y + 0.2]);
  }
  STROKE_CACHE[ch] = segs;
  return segs;
}
